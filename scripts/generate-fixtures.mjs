// Regenerate tests/fixtures/neverthrow.d.ts from the installed neverthrow types.
// neverthrow ships a single bundled dist/index.d.ts; stripping its trailing
// `export { ... }` turns the file from a module into a script, which makes all
// `declare`d identifiers ambient globals visible to the rule tester's snippets.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(resolve(root, 'node_modules/neverthrow/dist/index.d.ts'), 'utf8')

const stripped = src.replace(/^export\s*\{[^}]*\};?\s*$/gm, '').trimEnd()

const helpers = `

// --- test-only helpers ---
declare function getResult(): Result<string, Error>
declare function getResultAsync(): ResultAsync<string, Error>
declare function getNormal(): number
declare const obj: { get: () => Result<string, Error> }
`

const banner = `// AUTO-GENERATED by scripts/generate-fixtures.mjs from node_modules/neverthrow/dist/index.d.ts.
// Run \`npm run generate:fixtures\` to refresh after upgrading neverthrow.

`

const out = resolve(root, 'tests/fixtures/neverthrow.d.ts')
writeFileSync(out, banner + stripped + helpers)
